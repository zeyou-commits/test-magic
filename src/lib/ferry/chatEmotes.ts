const labelOf = (code: string) =>
  code
    .replace(/^[a-z]_(\d+_)?/, "")
    .replace(/_/g, " ")
    .replace(/^./, (first) => first.toUpperCase());

/** La banque complète, sans doublon d'image : les humeurs d'abord, puis les autres cabas. */
export function emoteBank(moods: EmoteRef[]): EmoteRef[] {
  const seen = new Set<string>();
  const unique = moods.filter((mood) => !seen.has(mood.image) && seen.add(mood.image));
  return [
    ...unique,
    ...FILE_EMOTES.filter(([, image]) => !seen.has(image)).map(([code, image]) => ({
      code,
      image,
      label: labelOf(code),
    })),
  ];
}

/** Pour lire un message : tous les codes comptent, même ceux qu'un doublon cache du panneau. */
export function emoteDictionary(moods: EmoteRef[]): EmoteRef[] {
  return [...moods, ...FILE_EMOTES.map(([code, image]) => ({ code, image, label: labelOf(code) }))];
}

