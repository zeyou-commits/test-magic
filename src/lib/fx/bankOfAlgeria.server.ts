const CA = [...rootCertificates, DIGICERT_G2_TLS_CA1];

/** Lit une page du site de la Banque d'Algérie (texte), en 9 s au plus. */
export function fetchBankOfAlgeria(url: string, timeoutMs = 9000): Promise<string> {
  return new Promise((resolve, reject) => {
    const req = request(
      url,
      { ca: CA, headers: { accept: "text/html" }, timeout: timeoutMs },
      (res) => {
        if ((res.statusCode ?? 0) >= 400) {
          res.resume();
          reject(new Error(`Source indisponible (${res.statusCode})`));
          return;
        }
        res.setEncoding("utf8");
        let body = "";
        res.on("data", (chunk: string) => {
          body += chunk;
          if (body.length > 2_000_000) req.destroy(new Error("Réponse trop volumineuse"));
        });
        res.on("end", () => resolve(body));
      },
    );
    req.on("timeout", () => req.destroy(new Error("Délai dépassé")));
    req.on("error", reject);
    req.end();
  });
}
